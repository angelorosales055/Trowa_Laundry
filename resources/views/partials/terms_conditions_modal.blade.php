<script>
    function openTermsModal() {
        const modal = document.getElementById('terms-modal');
        if (modal) {
            modal.classList.remove('hidden');
            modal.classList.add('flex');
            document.body.classList.add('overflow-hidden');
        }
    }

    function closeTermsModal() {
        const modal = document.getElementById('terms-modal');
        if (modal) {
            modal.classList.add('hidden');
            modal.classList.remove('flex');
            document.body.classList.remove('overflow-hidden');
        }
    }

    function acceptTermsFromModal() {
        // Auto-check terms checkbox if on register or login page
        const regCheck = document.getElementById('register-terms');
        if (regCheck) regCheck.checked = true;

        const loginCheck = document.getElementById('login-terms-check');
        if (loginCheck) loginCheck.checked = true;

        const custLoginCheck = document.getElementById('cust-login-terms-check');
        if (custLoginCheck) custLoginCheck.checked = true;

        closeTermsModal();
    }

    // Close on backdrop click
    document.getElementById('terms-modal')?.addEventListener('click', function(e) {
        if (e.target === this) {
            closeTermsModal();
        }
    });

    // Close on Escape key
    document.addEventListener('keydown', function(e) {
        if (e.key === 'Escape') {
            closeTermsModal();
        }
    });
</script>
